/**
 * Generates supabase/seed.sql from the TypeScript sources.
 *
 * The data in packages/core is the authority until the admin exists. Rather
 * than maintain the same wines twice, this walks those modules and emits the
 * inserts, so a fresh Supabase project can be populated with one paste.
 *
 * Run: node scripts/generate-seed.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const core = join(root, 'packages/core/src');

/** Escape a value for a SQL string literal, or emit NULL. */
const s = (v) => (v === undefined || v === null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === undefined || v === null ? 'NULL' : Number(v));
const arr = (v) =>
  !v || v.length === 0 ? `'{}'` : `ARRAY[${v.map((x) => s(x)).join(', ')}]::text[]`;

/**
 * Pulls an exported array literal out of a .ts file and evaluates it.
 *
 * These modules are plain data with no imports at runtime, so stripping the
 * type-only lines and evaluating the literal is safe and avoids needing a
 * TypeScript build step just to read our own constants.
 */
function readExportedArray(file, name) {
  const src = readFileSync(join(core, file), 'utf8');
  const start = src.indexOf(`export const ${name}`);
  if (start === -1) throw new Error(`${name} not found in ${file}`);
  // Seek past the type annotation first - `: readonly Wine[] =` contains a `[`
  // that is not the literal, and grabbing it yields a silent empty array.
  const assign = src.indexOf('=', start);
  if (assign === -1) throw new Error(`no assignment for ${name} in ${file}`);
  const open = src.indexOf('[', assign);
  let depth = 0;
  let end = -1;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '[') depth++;
    else if (src[i] === ']') {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error(`unterminated array for ${name}`);
  // eslint-disable-next-line no-new-func
  return new Function(`return ${src.slice(open, end)};`)();
}

const MENU = readExportedArray('menu.ts', 'MENU');
const WINES = readExportedArray('wines.ts', 'WINES');
const BAR_LIST = readExportedArray('drinks.ts', 'BAR_LIST');

// An empty parse is always a bug here, never legitimate - fail loudly rather
// than writing a seed file that silently inserts nothing.
for (const [label, data] of [['MENU', MENU], ['WINES', WINES], ['BAR_LIST', BAR_LIST]]) {
  if (!Array.isArray(data) || data.length === 0) {
    throw new Error(`parsed ${label} as empty - the extractor is broken, not the data`);
  }
}

const out = [];
out.push('-- Seed data for Ta-nnin.');
out.push('-- GENERATED by scripts/generate-seed.mjs - do not edit by hand.');
out.push('-- Run after 0001_init.sql. Safe to re-run: it truncates first.');
out.push('');
out.push('begin;');
out.push('');
out.push('truncate menu_items, menu_sections, wines, drinks, drink_sections restart identity cascade;');
out.push('');

// ── menu ─────────────────────────────────────────────────────────────────────
out.push('-- menu sections and items, from both printed cards');
MENU.forEach((section, i) => {
  out.push(
    `insert into menu_sections (id, title, service, position) values (${s(section.id)}, ${s(section.title)}, ${s(section.service)}, ${i});`,
  );
});
out.push('');

MENU.forEach((section) => {
  section.items.forEach((item, i) => {
    const ranged = Array.isArray(item.price);
    const price = ranged ? item.price[0] : item.price;
    const priceMax = ranged ? item.price[1] : null;
    out.push(
      `insert into menu_items (section_id, name, note, price, price_max, with_crackers, position) values (` +
        `${s(section.id)}, ${s(item.name)}, ${s(item.note)}, ${n(price)}, ${n(priceMax)}, ${item.withCrackers ? 'true' : 'false'}, ${i});`,
    );
  });
});
out.push('');

// ── wines ────────────────────────────────────────────────────────────────────
out.push(`-- the cellar: ${WINES.length} bottles`);
WINES.forEach((w, i) => {
  out.push(
    `insert into wines (name, producer, colour, country, region, grapes, vintage, bottle, position) values (` +
      `${s(w.name)}, ${s(w.producer)}, ${s(w.colour)}, ${s(w.country)}, ${s(w.region)}, ${arr(w.grapes)}, ${n(w.vintage)}, ${n(w.bottle)}, ${i});`,
  );
});
out.push('');

// ── the bar list ─────────────────────────────────────────────────────────────
// Everything by the glass or by the serve, in its own tables. This is the list
// the QR code opens and the one Tawat edits, so it is modelled as the bar sees
// it - one list - rather than split across `wines` and something else.
const barCount = BAR_LIST.reduce((t, s) => t + s.items.length, 0);
out.push(`-- the bar list: ${barCount} pours across ${BAR_LIST.length} sections`);
BAR_LIST.forEach((section, i) => {
  out.push(
    `insert into drink_sections (id, title, is_wine, position) values (` +
      `${s(section.id)}, ${s(section.title)}, ${section.isWine ? 'true' : 'false'}, ${i});`,
  );
});
out.push('');

BAR_LIST.forEach((section) => {
  section.items.forEach((d, i) => {
    out.push(
      `insert into drinks (section_id, name, note, price, sold_out, position) values (` +
        `${s(section.id)}, ${s(d.name)}, ${s(d.note)}, ${n(d.price)}, ${d.soldOut ? 'true' : 'false'}, ${i});`,
    );
  });
});
out.push('');
out.push('commit;');
out.push('');

const dest = join(root, 'supabase/seed.sql');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out.join('\n'), 'utf8');

const items = MENU.reduce((t, s) => t + s.items.length, 0);
console.log(`menu sections : ${MENU.length}`);
console.log(`menu items    : ${items}`);
console.log(`wines         : ${WINES.length}`);
console.log(`bar sections  : ${BAR_LIST.length}`);
console.log(`bar pours     : ${barCount}`);
console.log(`-> ${dest} (${out.length} lines)`);
